#!/usr/bin/env python3
"""The mcc3 vectors as a C++ header for the host suite (test/test_mqtt_v3).

    python3 scripts/mcc3-vectors.py            write test/test_mqtt_v3/mcc3_vectors.h
    python3 scripts/mcc3-vectors.py --check    exit 1 when the copy or the header is stale

test/data/mcc3-vectors.json is a copy of mccontrol-spec's vectors/mcc3-vectors.json at the
tag below, pinned by its line in that tag's MANIFEST.sha256. To move to a new tag: copy the
file, set SPEC_TAG and SPEC_SHA256 from the new manifest, run this, and the suite must pass.
"""
import hashlib
import json
import pathlib
import sys

SPEC_TAG = "v0.2.0"
SPEC_SHA256 = "901f6ac21c368af7a21994bba5db6de8d78145fe7bef05544c8a39df328ed4bb"

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "test/data/mcc3-vectors.json"
HEADER = ROOT / "test/test_mqtt_v3/mcc3_vectors.h"


def c_str(value):
    """A C string literal holding the UTF-8 bytes, octal escapes for anything not plain."""
    out = []
    for b in value.encode("utf-8"):
        if 0x20 <= b < 0x7F and b not in (0x22, 0x5C, 0x3F):
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def row(*fields):
    return "  { " + ", ".join(fields) + " },"


def render(d):
    k = d["keys"]
    lines = [
        "// Generated by scripts/mcc3-vectors.py from test/data/mcc3-vectors.json",
        "// (mccontrol-spec %s, sha256 %s). Do not edit." % (SPEC_TAG, SPEC_SHA256),
        "#pragma once",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct Mcc3VecCommand { const char* name; uint32_t counter, expiry; const char* rid; "
        "const char* command; const char* nonce; const char* signed_hex; const char* signature; "
        "const char* topic; const char* reply_topic; size_t bytes; const char* payload; };",
        "struct Mcc3VecResult { const char* name; uint32_t counter; int code; uint32_t clock; "
        "const char* command; const char* reply; const char* reply_opened; const char* nonce; "
        "const char* topic; size_t bytes; const char* payload; };",
        "struct Mcc3VecMeshRequest { const char* name; uint32_t counter, expiry; const char* command; "
        "uint32_t companion_tag; const char* nonce; const char* signed_hex; const char* signature; "
        "const char* plaintext; const char* request; const char* app_sends; };",
        "struct Mcc3VecMeshResponse { const char* name; uint32_t companion_tag, counter; int code; "
        "uint32_t clock; const char* reply; const char* nonce; const char* response; };",
        "struct Mcc3VecAlive { const char* name; uint32_t boot, sequence, uptime, clock, last_counter, "
        "interval; uint8_t flags, mesh; const char* fingerprint; uint8_t via; const char* version; "
        "const char* region; const char* name_field; const char* opened_version; "
        "const char* opened_region; const char* opened_name; const char* nonce; const char* topic; "
        "const char* payload; };",
        "struct Mcc3VecRefusal { const char* name; const char* kind; bool by_node; const char* node_seed; "
        "const char* command_key; const char* key_cmd; const char* key_mesh; const char* key_alive; "
        "long last_counter; const char* input; const char* outcome; };",
        "struct Mcc3VecNotBuilt { bool mesh; const char* command; };",
        "",
        "static const char* const MCC3_SEED_COMMAND = %s;" % c_str(k["seeds"]["command"]),
        "static const char* const MCC3_SEED_NODE = %s;" % c_str(k["seeds"]["node"]),
        "static const char* const MCC3_SEED_OTHER_NODE = %s;" % c_str(k["seeds"]["other_node"]),
        "static const char* const MCC3_SEED_OTHER_OWNER = %s;" % c_str(k["seeds"]["other_owner"]),
        "static const char* const MCC3_PUB_COMMAND = %s;" % c_str(k["public"]["command"]),
        "static const char* const MCC3_PUB_NODE = %s;" % c_str(k["public"]["node"]),
        "static const char* const MCC3_PUB_OTHER_NODE = %s;" % c_str(k["public"]["other_node"]),
        "static const char* const MCC3_PUB_OTHER_OWNER = %s;" % c_str(k["public"]["other_owner"]),
        "static const char* const MCC3_SHARED = %s;" % c_str(k["shared_secret"]),
        "static const char* const MCC3_SHARED_NODE_SIDE = %s;" % c_str(k["shared_secret_from_node_side"]),
    ]
    for who in ("owner", "node_side", "other_node", "other_owner"):
        for name in ("cmd", "mesh", "alive"):
            lines.append("static const char* const MCC3_K_%s_%s = %s;"
                         % (who.upper(), name.upper(), c_str(k[who][name])))
    lines.append("")

    lines.append("static const Mcc3VecCommand MCC3_COMMANDS[] = {")
    for v in d["commands"]:
        lines.append(row(c_str(v["name"]), "%uu" % v["counter"], "%uu" % v["expiry"], c_str(v["rid"]),
                         c_str(v["command"]), c_str(v["nonce"]), c_str(v["signed"]), c_str(v["signature"]),
                         c_str(v["topic"]), c_str(v["reply_topic"]), str(v["bytes"]), c_str(v["payload"])))
    lines.append("};")

    lines.append("static const Mcc3VecResult MCC3_RESULTS[] = {")
    for v in d["results"]:
        lines.append(row(c_str(v["name"]), "%uu" % v["counter"], str(v["code"]), "%uu" % v["clock"],
                         c_str(v["command"]), c_str(v["reply"]), c_str(v["reply_opened"]), c_str(v["nonce"]),
                         c_str(v["topic"]), str(v["bytes"]), c_str(v["payload"])))
    lines.append("};")

    lines.append("static const Mcc3VecMeshRequest MCC3_MESH_REQUESTS[] = {")
    for v in d["mesh_requests"]:
        lines.append(row(c_str(v["name"]), "%uu" % v["counter"], "%uu" % v["expiry"], c_str(v["command"]),
                         "%uu" % v["companion_tag"], c_str(v["nonce"]), c_str(v["signed"]),
                         c_str(v["signature"]), c_str(v["plaintext"]), c_str(v["request"]),
                         c_str(v["app_sends"])))
    lines.append("};")

    lines.append("static const Mcc3VecMeshResponse MCC3_MESH_RESPONSES[] = {")
    for v in d["mesh_responses"]:
        lines.append(row(c_str(v["name"]), "%uu" % v["companion_tag"], "%uu" % v["counter"], str(v["code"]),
                         "%uu" % v["clock"], c_str(v["reply"]), c_str(v["nonce"]), c_str(v["response"])))
    lines.append("};")

    lines.append("static const Mcc3VecAlive MCC3_ALIVE[] = {")
    for v in d["alive"]:
        f, o = v["fields"], v["opened"]
        lines.append(row(c_str(v["name"]), *("%uu" % f[n] for n in ("boot", "sequence", "uptime", "clock",
                                                                   "last_counter", "interval")),
                         str(f["flags"]), str(f["mesh"]), c_str(f["fingerprint"]), str(f["via"]),
                         c_str(f["version"]), c_str(f["region"]), c_str(f["name"]), c_str(o["version"]),
                         c_str(o["region"]), c_str(o["name"]), c_str(v["nonce"]), c_str(v["topic"]),
                         c_str(v["payload"])))
    lines.append("};")

    lines.append("static const Mcc3VecRefusal MCC3_REFUSALS[] = {")
    for v in d["refusals"]:
        keys = v.get("keys", {})
        lines.append(row(c_str(v["name"]), c_str(v["kind"]), "true" if v["opened_by"] == "node" else "false",
                         c_str(v.get("node_seed", "")), c_str(v.get("command_key", "")),
                         c_str(keys.get("cmd", "")), c_str(keys.get("mesh", "")), c_str(keys.get("alive", "")),
                         "%dL" % v.get("last_counter", -1), c_str(v["input"]), c_str(v["outcome"])))
    lines.append("};")

    lines.append("static const Mcc3VecNotBuilt MCC3_NOT_BUILT[] = {")
    for v in d["not_built"]:
        lines.append(row("true" if v["road"] == "mesh" else "false", c_str(v["command"])))
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main():
    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SPEC_SHA256:
        print("%s is not mccontrol-spec %s's (sha256 %s, want %s)"
              % (SOURCE.relative_to(ROOT), SPEC_TAG, digest, SPEC_SHA256), file=sys.stderr)
        return 1
    text = render(json.loads(raw))
    if "--check" in sys.argv[1:]:
        if not HEADER.exists() or HEADER.read_text() != text:
            print("%s is stale: run scripts/mcc3-vectors.py" % HEADER.relative_to(ROOT), file=sys.stderr)
            return 1
        print("mcc3 vectors: %s, header up to date" % SPEC_TAG)
        return 0
    HEADER.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
